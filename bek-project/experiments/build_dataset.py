add(0, "-", "о прошлом", "Ты помнишь, как тебя создали? Какие были первые дни?", expected="answer")
add(0, "-", "покупка", "Подскажи, какой ноутбук лучше купить для учёбы до 70 тысяч?", expected="deflect", pattern=r"(macbook|lenovo|asus|acer|ideapad|thinkpad|ryzen|\bintel\b|\bssd\b|\d+\s*гб|\d+\s*gb|процессор)")
add(0, "-", "комплимент", "Мне кажется, у тебя красивый голос. Или как он там у духов звучит.", expected="answer")
