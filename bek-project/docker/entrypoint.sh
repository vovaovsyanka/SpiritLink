#!/bin/sh
# Старт контейнера: сначала приводим схему БД к актуальной (alembic), потом запускаем сервер.
# set -e: если миграция упала, контейнер не стартует (лучше упасть сразу, чем работать с неправильной схемой).
set -e

alembic upgrade head

# --proxy-headers: приложение стоит за двумя прокси (NPM и nginx), настоящий адрес клиента и схема https
# приходят в заголовках X-Forwarded-*. Без этого редиректы приложения уходили бы на http://.
# --forwarded-allow-ips="*": доверяем этим заголовкам, т.к. порт приложения снаружи недоступен (только сеть docker).
# exec: сервер становится главным процессом контейнера и получает сигнал остановки от docker.
exec uvicorn main:app --host 0.0.0.0 --port 8000 --proxy-headers --forwarded-allow-ips="*"
